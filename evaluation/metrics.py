"""
Metrics for evaluating Text-to-SQL performance.
"""

import re
import sqlite3
from typing import List, Any, Optional
from dataclasses import dataclass


def preprocess_gold_sql(sql: str) -> str:
    """
    Fix common issues in gold SQL from datasets.
    
    Known issues:
    - '! =' with spaces -> '!='
    - Extra trailing ')' 
    - Extra whitespace
    """
    if not sql:
        return sql
    
    # Fix '! =' with spaces -> '!='
    sql = re.sub(r'!\s*=', '!=', sql)
    
    # Fix '< >' with spaces -> '<>'
    sql = re.sub(r'<\s*>', '<>', sql)
    
    # Fix trailing unbalanced ')'
    # Count parens and remove trailing ) if unbalanced
    open_count = sql.count('(')
    close_count = sql.count(')')
    if close_count > open_count:
        # Remove trailing ) that are unbalanced
        diff = close_count - open_count
        sql = sql.rstrip()
        while diff > 0 and sql.endswith(')'):
            sql = sql[:-1].rstrip()
            diff -= 1
    
    # Normalize whitespace
    sql = ' '.join(sql.split())
    
    return sql


@dataclass
class ExecutionResult:
    """Result of executing a SQL query."""
    success: bool
    results: List[Any]
    error: Optional[str] = None


def execute_sql(conn: sqlite3.Connection, sql: str) -> ExecutionResult:
    """
    Execute SQL and return results.
    
    Args:
        conn: Database connection
        sql: SQL query to execute
    
    Returns:
        ExecutionResult with success status and results
    """
    try:
        cursor = conn.cursor()
        cursor.execute(sql)
        results = cursor.fetchall()
        return ExecutionResult(success=True, results=results)
    except sqlite3.Error as e:
        return ExecutionResult(success=False, results=[], error=str(e))


def normalize_results(results: List[Any]) -> List[tuple]:
    """
    Normalize query results for comparison.
    
    - Convert to tuples
    - Sort rows (order-insensitive comparison)
    - Round floats to handle precision differences
    """
    normalized = []
    for row in results:
        normalized_row = []
        for val in row:
            if isinstance(val, float):
                # Round to 4 decimal places for comparison
                normalized_row.append(round(val, 4))
            else:
                normalized_row.append(val)
        normalized.append(tuple(normalized_row))
    
    # Sort for order-insensitive comparison
    return sorted(normalized, key=lambda x: str(x))


def execution_accuracy(
    conn: sqlite3.Connection,
    generated_sql: str,
    gold_sql: str,
) -> dict:
    """
    Compare execution results of generated SQL vs gold SQL.
    
    Args:
        conn: Database connection
        generated_sql: SQL generated by the agent
        gold_sql: Ground truth SQL
    
    Returns:
        dict with:
            - passed: bool
            - generated_results: list
            - gold_results: list
            - generated_sql_time_ms: float
            - gold_sql_time_ms: float
            - error: str or None
    """
    import time
    
    # Execute generated SQL with timing
    gen_start = time.time()
    gen_result = execute_sql(conn, generated_sql)
    gen_time_ms = (time.time() - gen_start) * 1000
    
    if not gen_result.success:
        return {
            "passed": False,
            "generated_results": [],
            "gold_results": [],
            "generated_sql_time_ms": round(gen_time_ms, 2),
            "gold_sql_time_ms": 0,
            "error": f"Generated SQL failed: {gen_result.error}",
        }
    
    # Preprocess and execute gold SQL with timing
    gold_sql_clean = preprocess_gold_sql(gold_sql)
    gold_start = time.time()
    gold_result = execute_sql(conn, gold_sql_clean)
    gold_time_ms = (time.time() - gold_start) * 1000
    
    if not gold_result.success:
        return {
            "passed": False,
            "generated_results": gen_result.results,
            "gold_results": [],
            "generated_sql_time_ms": round(gen_time_ms, 2),
            "gold_sql_time_ms": round(gold_time_ms, 2),
            "error": f"Gold SQL failed: {gold_result.error}",
        }
    
    # Normalize and compare
    gen_normalized = normalize_results(gen_result.results)
    gold_normalized = normalize_results(gold_result.results)
    
    passed = gen_normalized == gold_normalized
    
    return {
        "passed": passed,
        "generated_results": gen_result.results,
        "gold_results": gold_result.results,
        "generated_sql_time_ms": round(gen_time_ms, 2),
        "gold_sql_time_ms": round(gold_time_ms, 2),
        "error": None if passed else "Results do not match",
    }


def compute_summary(results: List[dict]) -> dict:
    """
    Compute aggregate metrics from evaluation results.
    
    Args:
        results: List of per-question result dicts
    
    Returns:
        Summary dict with accuracy, timing stats
    """
    total = len(results)
    passed = sum(1 for r in results if r.get("passed", False))
    
    # Timing stats
    latencies = [r.get("total_latency_ms", 0) for r in results if r.get("total_latency_ms")]
    
    return {
        "total": total,
        "passed": passed,
        "failed": total - passed,
        "accuracy": round(passed / total, 4) if total > 0 else 0,
        "avg_latency_ms": round(sum(latencies) / len(latencies), 2) if latencies else 0,
        "min_latency_ms": round(min(latencies), 2) if latencies else 0,
        "max_latency_ms": round(max(latencies), 2) if latencies else 0,
    }
